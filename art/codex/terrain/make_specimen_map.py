#!/usr/bin/env python3
"""Write scripts/board-mock-maps/oriented-specimens.txt: an ASCII board-mock map
that puts every oriented river / plains-road shape the r1 set covers on one
board (the showcase map exercises only a few), and report which shape each
specimen resolves to through board-mock's port of the frontend selection.

Each fork specimen is a centre hex with a two-hex arm out of each connected
edge (a straight, then an end). Fan forks (three consecutive edges) cannot be
authored this way: their arms are mutually adjacent, so the frontend's
junction-chord pruning re-routes them. They are reviewed with
`paintin.py preview` instead (explicit edge sets).

    python3 art/codex/terrain/make_specimen_map.py
"""

from __future__ import annotations

import importlib.util
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "scripts" / "board-mock-maps" / "oriented-specimens.txt"
spec = importlib.util.spec_from_file_location("board_mock", REPO / "scripts" / "board-mock.py")
bm = importlib.util.module_from_spec(spec)
sys.modules["board_mock"] = bm
spec.loader.exec_module(bm)  # type: ignore[union-attr]

DIRS = bm.AXIAL_DIRECTIONS
COLS, ROWS = 34, 26
NON_FAN_FORKS = [(0, 2, 5), (1, 2, 5), (0, 1, 3), (0, 2, 3), (0, 3, 4), (0, 3, 5),
                 (0, 2, 4), (1, 3, 5), (0, 4, 5)]


def to_offset(q: int, r: int) -> tuple[int, int]:
    return q, r + (q - (q & 1)) // 2


def main() -> None:
    terrain = [["." for _ in range(COLS)] for _ in range(ROWS)]
    roads = [["." for _ in range(COLS)] for _ in range(ROWS)]

    def put(q: int, r: int, ch: str, road: bool = False) -> None:
        c, row = to_offset(q, r)
        if not (0 <= c < COLS and 0 <= row < ROWS):
            raise ValueError(f"specimen hex ({q},{r}) off the map")
        if road:
            roads[row][c] = "#"
        else:
            terrain[row][c] = ch

    centres = []
    # river forks (top half) and road forks (bottom half), 5 columns apart
    for i, mask in enumerate(NON_FAN_FORKS):
        for half, road in ((0, False), (1, True)):
            col = 2 + (i % 5) * 6
            row = 4 + (i // 5) * 6 + half * 13
            q, r = col, row - (col - (col & 1)) // 2
            centres.append((q, r, mask, road))
            put(q, r, "~", road)
            for e in mask:
                dq, dr = DIRS[e]
                put(q + dq, r + dr, "~", road)
                put(q + 2 * dq, r + 2 * dr, "~", road)
    # extras along the right column (axial): a pond, bridges on both turn
    # shapes and one on a "\\" straight (no oriented bridge art -> generic 00)
    def at(col: int, row: int) -> tuple[int, int]:
        return col, row - (col - (col & 1)) // 2

    def step(h: tuple[int, int], e: int, n: int = 1) -> tuple[int, int]:
        return h[0] + n * DIRS[e][0], h[1] + n * DIRS[e][1]

    put(*at(31, 2), "~")  # pond: a river hex with no river neighbours
    for row, river_edges in ((7, (0, 4)), (13, (1, 3)), (19, (0, 3))):
        b = at(31, row)
        put(*b, "=")
        put(*b, "=", road=True)
        for e in river_edges:
            put(*step(b, e), "~")
            put(*step(b, e, 2), "~")
        for e in (2, 5):
            put(*step(b, e), ".", road=True)
    text = ["; Oriented-shape specimens for the r1 river/road/bridge candidates (generated by",
            ";   art/codex/terrain/make_specimen_map.py). Rivers top, plains roads bottom;",
            ";   each fork has a straight + end arm per edge. Right column: a pond, a bridge",
            ";   on turn_se_sw and on turn_ne_nw, and one on a straight_d (generic 00).",
            "[terrain]"] + ["".join(r) for r in terrain] + ["[roads]"] + ["".join(r) for r in roads]
    OUT.write_text("\n".join(text) + "\n")
    game = bm.load_map(OUT)
    probe = game.terrain_at
    course = bm.river_course_edges([(h.q, h.r) for h in game.hexes], probe)
    counts: Counter[str] = Counter()
    for h in game.hexes:
        key = bm._hex_key(h.q, h.r)
        if key in course:
            t = bm.oriented_river_tile(course[key])
            counts[f"{h.terrain}/{t.name if t else '00'}{'*' if t and t.mirror else ''}"] += 1
    for ref in bm.road_tile_refs(game.hexes, game.hex_at).values():
        counts[f"{ref.lookup}{'*' if ref.mirror else ''}"] += 1
    for k in sorted(counts):
        print(f"{counts[k]:3d} {k}")


if __name__ == "__main__":
    main()
