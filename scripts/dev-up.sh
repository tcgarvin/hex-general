#!/usr/bin/env bash
#
# Bring up the local Supabase stack for offline laptop playtesting (Phase 7,
# Slice 3). Idempotent: safe to re-run.
#
# It:
#   1. generates a throwaway local ES256 JWT signing key (if absent) so local
#      Auth signs tokens the API verifies unchanged (ES256 via JWKS),
#   2. `supabase start`s Postgres + Auth + Studio from supabase/config.toml,
#   3. seeds the @hex.local dev accounts (api/app/dev_seed.py),
#   4. writes api/.env (SUPABASE_URL / SERVICE_ROLE_KEY / DEV_USER_IDS) and
#      frontend/.env.local (pointing the browser app at the local stack).
#
# Then: start the API (`cd api && uv run uvicorn app.main:app --reload --port 8080`)
# and the frontend (`cd frontend && npm run dev`), and sign in as dev1@hex.local.
# See docs/LOCAL_DEV.md. Tear down with scripts/dev-down.sh.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SIGNING_KEY="$REPO/supabase/signing_keys.json"
API_ENV="$REPO/api/.env"
FE_ENV="$REPO/frontend/.env.local"

# --- locate the Supabase CLI ---
if command -v supabase >/dev/null 2>&1; then
  SUPABASE="supabase"
elif [ -x "$HOME/.local/bin/supabase" ]; then
  SUPABASE="$HOME/.local/bin/supabase"
else
  echo "error: supabase CLI not found. Install it: https://supabase.com/docs/guides/local-development" >&2
  exit 1
fi

# --- preflight: Docker must be running and reachable ---
if ! docker info >/dev/null 2>&1; then
  echo "error: Docker is not running (or this user can't reach the daemon)." >&2
  echo "       Start Docker, e.g. 'sudo systemctl start docker', and ensure you're in the 'docker' group." >&2
  exit 1
fi

# --- 1. local ES256 signing key (throwaway, gitignored) ---
# The CLI writes a JWKS *array* to the configured signing_keys_path; seed an
# empty array, then --append one ES256 key. -s guards against a half-written
# (zero-byte) file from an interrupted run.
if [ ! -s "$SIGNING_KEY" ]; then
  echo "Generating local ES256 JWT signing key -> supabase/signing_keys.json"
  echo '[]' >"$SIGNING_KEY"
  if ! "$SUPABASE" gen signing-key --algorithm ES256 --append --workdir "$REPO" >/dev/null 2>&1; then
    rm -f "$SIGNING_KEY"
    echo "error: failed to generate local signing key (supabase gen signing-key)." >&2
    exit 1
  fi
fi

# --- 2. start the stack (idempotent: start is a no-op if already running) ---
echo "Starting local Supabase stack (this may pull Docker images on first run)..."
"$SUPABASE" start --workdir "$REPO" || {
  echo "error: 'supabase start' failed. See output above." >&2
  exit 1
}

# Read connection details. `status -o env` prints sourceable KEY="value" lines.
STATUS_ENV="$("$SUPABASE" status --workdir "$REPO" -o env 2>/dev/null)"
eval "$STATUS_ENV"

if [ -z "${API_URL:-}" ] || [ -z "${SERVICE_ROLE_KEY:-}" ] || [ -z "${ANON_KEY:-}" ]; then
  echo "error: could not read API_URL / SERVICE_ROLE_KEY / ANON_KEY from 'supabase status'." >&2
  exit 1
fi

# --- 3. write api/.env (without DEV_USER_IDS yet) ---
cat >"$API_ENV" <<EOF
# Generated by scripts/dev-up.sh for the local Supabase stack. Not committed.
# Re-run scripts/dev-up.sh to refresh. See docs/LOCAL_DEV.md.
SUPABASE_URL=$API_URL
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
EOF

# --- 4. seed dev accounts and capture the DEV_USER_IDS line ---
echo "Seeding dev accounts..."
SEED_OUT="$(cd "$REPO/api" && uv run python -m app.dev_seed)" || {
  echo "error: seeding failed:" >&2
  echo "$SEED_OUT" >&2
  exit 1
}
echo "$SEED_OUT"
DEV_IDS_LINE="$(echo "$SEED_OUT" | grep -E '^DEV_USER_IDS=' | tail -1)"
if [ -z "$DEV_IDS_LINE" ]; then
  echo "error: seed did not emit a DEV_USER_IDS line." >&2
  exit 1
fi
echo "$DEV_IDS_LINE" >>"$API_ENV"

# --- 5. point the frontend at the local stack (backing up the original once) ---
if [ -f "$FE_ENV" ] && [ ! -f "$FE_ENV.bak" ]; then
  cp "$FE_ENV" "$FE_ENV.bak"
  echo "Backed up your existing frontend/.env.local -> frontend/.env.local.bak"
fi
cat >"$FE_ENV" <<EOF
# Generated by scripts/dev-up.sh — points the Vite app at the local stack.
# Your previous .env.local (if any) is saved as .env.local.bak.
# scripts/dev-down.sh restores it.
VITE_SUPABASE_URL=$API_URL
VITE_SUPABASE_ANON_KEY=$ANON_KEY
VITE_API_URL=http://localhost:8080
EOF

cat <<EOF

Local stack is up. Next:
  1. API:       cd api && uv run uvicorn app.main:app --reload --port 8080
  2. Frontend:  cd frontend && npm run dev
  3. Open the app, sign in with email/password:
       dev1@hex.local  (and dev2@hex.local) — password: see api/app/dev_seed.py
  4. Use the dev-profile switcher to act as the other identity and play both sides.

Supabase Studio: ${STUDIO_URL:-http://127.0.0.1:54323}
Tear down with:  ./scripts/dev-down.sh
EOF
