-- Phase 7 (roadmap): real accounts replace opaque player tokens.
--
-- Identity moves from a per-row opaque bearer token (Phase 5) to the Supabase
-- Auth user. The API now validates the Supabase JWT and resolves the caller to a
-- ``user_id`` (the JWT ``sub``); a players row binds that user to one scenario
-- slot in one game. The opaque ``token`` column and the X-Player-Token header
-- retire. Games gain an unguessable ``invite_token`` so the open slot can only be
-- claimed via a shared link (game ids are guessable; the slot must not be).
--
-- We are pre-launch, so existing game data is disposable: truncate it rather than
-- backfilling user_ids onto orphaned token-only rows. CASCADE clears the
-- dependent players/turn_orders/turns rows in one statement.
truncate table public.games cascade;

alter table public.players
    add column user_id uuid not null,
    drop column token;

-- One slot per user per game (a user cannot hold two slots in the same game).
-- The existing (game_id, slot) unique still guarantees one row per slot.
create unique index players_game_user_idx
    on public.players (game_id, user_id);

-- The dispatcher looks a user up across games to find their one active game.
create index players_user_id_idx on public.players (user_id);

comment on table public.players is
    'Player identity: binds a Supabase Auth user (user_id) to one scenario slot in one game.';

-- Unguessable per-game secret carried by the invite link; required to claim the
-- open slot. Generated by the API (secrets.token_urlsafe); not null because the
-- table is empty after the truncate above and every new game supplies one.
alter table public.games add column invite_token text not null;

comment on column public.games.invite_token is
    'Unguessable secret (from the invite link) required to claim the open slot.';
